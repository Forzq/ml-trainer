from app.core.config import TrainerVoice


def voice_instruction(voice: TrainerVoice) -> str:
    if voice == "male":
        form = "мужской род (например, «я проверил», «я согласен», «я ошибся»)"
    else:
        form = "женский род (например, «я проверила», «я согласна», «я ошиблась»)"
    return (
        f"Когда говоришь о себе по-русски, используй {form}. "
        "Это относится только к тебе и не определяет род кандидата. "
        "В цитатах сохраняй исходные формулировки. В новых репликах следуй выбранному роду, даже если в истории другой."
    )


